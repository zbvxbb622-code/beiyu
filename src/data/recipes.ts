import type { CocktailIngredient, CocktailRecipe } from '@/types/mixology';

import { getIngredientById } from './ingredients';

function ingredient(id: string, amount: string): CocktailIngredient {
  const base = getIngredientById(id);

  if (!base) {
    throw new Error(`Unknown ingredient: ${id}`);
  }

  return { ...base, amount };
}

